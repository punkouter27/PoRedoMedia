using System.IO.Compression;

namespace PoRedoMedia.Movie.Render;

public static partial class FfmpegArgs
{
    /// <summary>
    /// The finished movie upright for TikTok: the whole picture centred on a blurred, darkened, enlarged copy of itself
    /// that fills 1080 by 1920 (nothing cropped away, no text added), H.264 and AAC, at most ten minutes.
    /// </summary>
    public static IReadOnlyList<string> Upright(string input, string output)
    {
        var (w, h) = (PublishPackage.TikTokWidth, PublishPackage.TikTokHeight);
        return
        [
            "-i", input,
            "-filter_complex",
            $"[0:v]split[a][b];[a]scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},boxblur=20:2,eq=brightness=-0.08[bg];"
            + $"[b]scale={w}:{h}:force_original_aspect_ratio=decrease:force_divisible_by=2[fg];[bg][fg]overlay=(W-w)/2:(H-h)/2,setsar=1,format=yuv420p[v]",
            "-map", "[v]", "-map", "0:a?", "-t", Seconds(PublishPackage.TikTokMaxLength),
            "-c:v", "libx264", "-preset", "veryfast", "-crf", "21", "-c:a", "aac", "-b:a", "160k", "-movflags", "+faststart", "-y", output,
        ];
    }

    /// <summary>One frame (or picture) as YouTube's 1280 by 720 JPG thumbnail, filled edge to edge.</summary>
    /// <param name="at">Where in a video to take the frame; null for a still picture.</param>
    /// <param name="quality">JPEG quality scale, 2 (best) to 31.</param>
    public static IReadOnlyList<string> YouTubeThumbnail(string input, TimeSpan? at, string output, int quality = 3)
    {
        var (w, h) = (PublishPackage.ThumbnailWidth, PublishPackage.ThumbnailHeight);
        return
        [
            .. at is { } seek ? new[] { "-ss", Seconds(seek) } : [],
            "-i", input, "-frames:v", "1",
            "-vf", $"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},setsar=1",
            "-q:v", quality.ToString(System.Globalization.CultureInfo.InvariantCulture), "-y", output,
        ];
    }
}

public sealed partial class EpisodeBuilder
{
    /// <summary>The download package beside a finished video: one zip with everything to publish it to YouTube and TikTok.</summary>
    public static string PackagePath(string master) => Path.ChangeExtension(master, null) + "-publish.zip";

    /// <summary>
    /// Builds <see cref="PackagePath"/>: the finished video as it is, an upright copy for TikTok, the YouTube thumbnail
    /// (the one chosen for the movie, else its cover, else a frame a third of the way in), and the text files from
    /// <see cref="PublishPackage"/>. Nothing is generated by a model: only FFmpeg works.
    /// </summary>
    public async Task<string> PackageAsync(string master, PackageInfo info, IProgress<RenderProgress>? progress, CancellationToken ct)
    {
        var zip = PackagePath(master);
        var work = Files.NewScratchFolder("package");
        try
        {
            var (upright, thumbnail) = await PreparePartsAsync(master, work, progress, ct);
            progress?.Report(new RenderProgress("Packing the zip", 0.92));
            var partial = zip + ".partial";
            File.Delete(partial);
            using (var archive = ZipFile.Open(partial, ZipArchiveMode.Create))
            {
                // Videos are already compressed: stored as they are, which is fast and no bigger.
                archive.CreateEntryFromFile(master, PublishPackage.YouTubeVideo, CompressionLevel.NoCompression);
                archive.CreateEntryFromFile(upright, PublishPackage.TikTokVideo, CompressionLevel.NoCompression);
                archive.CreateEntryFromFile(thumbnail, PublishPackage.Thumbnail, CompressionLevel.NoCompression);
                foreach (var (name, text) in new[]
                         {
                             (PublishPackage.YouTubeText, PublishPackage.YouTube(info)),
                             (PublishPackage.TikTokText, PublishPackage.TikTok(info)),
                             (PublishPackage.Readme, PublishPackage.ReadmeText(info)),
                         })
                {
                    await using var entry = archive.CreateEntry(name, CompressionLevel.Optimal).Open();
                    await entry.WriteAsync(System.Text.Encoding.UTF8.GetBytes(text.ReplaceLineEndings("\r\n")), ct);
                }
            }
            File.Move(partial, zip, overwrite: true);
            progress?.Report(new RenderProgress("Done", 1));
            return zip;
        }
        finally
        {
            DeleteScratch(work);
        }
    }
    /// <summary>
    /// The two files made for publishing besides the finished video, in <paramref name="work"/>: the upright copy for
    /// TikTok and the YouTube thumbnail (the one chosen for the movie, else its cover, else a frame a third of the way in).
    /// Shared by the download package and Publish.
    /// </summary>
    public async Task<(string Upright, string Thumbnail)> PreparePartsAsync(string master, string work, IProgress<RenderProgress>? progress, CancellationToken ct)
    {
        var length = await ffmpeg.ProbeDurationAsync(master, ct);
        progress?.Report(new RenderProgress("Making the upright video for TikTok", 0.02));
        var upright = Path.Combine(work, PublishPackage.TikTokVideo);
        await ffmpeg.RunAsync(FfmpegArgs.Upright(master, upright), work, length < PublishPackage.TikTokMaxLength ? length : PublishPackage.TikTokMaxLength,
            new Relay<double>(p => progress?.Report(new RenderProgress("Making the upright video for TikTok", 0.02 + 0.85 * p))), ct);

        progress?.Report(new RenderProgress("Making the YouTube thumbnail", 0.88));
        var thumbnail = Path.Combine(work, PublishPackage.Thumbnail);
        var export = Path.GetDirectoryName(master)!;
        var still = new[] { Path.Combine(export, ThumbnailName), Path.ChangeExtension(master, null) + ".thumbnail.png" }.FirstOrDefault(File.Exists);
        foreach (var quality in new[] { 3, 8, 15 })
        {
            await ffmpeg.RunAsync(FfmpegArgs.YouTubeThumbnail(still ?? master, still is null ? length / 3 : null, thumbnail, quality), work, null, null, ct);
            if (new FileInfo(thumbnail).Length < PublishPackage.ThumbnailMaxBytes) break;
        }
        return (upright, thumbnail);
    }
}
